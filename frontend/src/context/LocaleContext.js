const LocaleContext = createContext(null);

export const LocaleProvider = ({ children }) => {
  const [locale, setLocaleState] = useState(
    () => localStorage.getItem('afrisupply_locale') || 'fr'
  );

  const setLocale = (l) => {
    localStorage.setItem('afrisupply_locale', l);
    setLocaleState(l);
  };

  /** Traduire une clé UI */
  const t = useCallback(
    (key) => T[locale]?.[key] ?? T.fr[key] ?? key,
    [locale]
  );

  /**
   * Traduire un champ d'un objet API.
   * tf(product, 'name') → product.name_en si locale=en et dispo, sinon product.name
   */
  const tf = useCallback(
    (obj, field) => {
      if (!obj) return '';
      if (locale === 'en') {
        const enVal = obj[`${field}_en`];
        if (enVal && enVal.trim()) return enVal;
      }
      return obj[field] ?? '';
    },
    [locale]
  );

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t, tf }}>
      {children}
    </LocaleContext.Provider>
  );
};

export const useLocale = () => {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error('useLocale must be used within a LocaleProvider');
  return ctx;
};

export default LocaleContext;