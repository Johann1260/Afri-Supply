const LocaleContext = createContext(null);

export const LocaleProvider = ({ children }) => {
  const [locale, setLocale] = useState(() => {
    try { return localStorage.getItem('afri_locale') || 'fr'; } catch { return 'fr'; }
  });

  const t = useCallback(
    (key) => T[locale]?.[key] ?? T.fr[key] ?? key,
    [locale]
  );

  const tf = useCallback(
    (obj, field) => {
      if (!obj || typeof obj !== 'object') return '';
      if (locale.startsWith('en')) {
        const enVal = obj[`${field}_en`];
        if (enVal && enVal.trim()) return enVal;
      }
      return obj[field] ?? '';
    },
    [locale]
  );

  const localizeAnon = useCallback(
    (name) => {
      if (!name || typeof name !== 'string') return name;
      const isEn = locale.startsWith('en');
      if (isEn && name.startsWith('Partenaire-'))
        return `Partner-${name.slice(11)}`;
      if (!isEn && name.startsWith('Partner-'))
        return `Partenaire-${name.slice(8)}`;
      return name;
    },
    [locale]
  );

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t, tf, localizeAnon }}>
      {children}
    </LocaleContext.Provider>
  );
};


export const useLocale = () => {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error('useLocale must be used within a LocaleProvider');
  return ctx;
};

export default LocaleContext;
